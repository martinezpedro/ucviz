def icon(
    name: str,
    size: int = 16,
    color: str = "currentColor",
    stroke_width: float = 2,
    cls: str = "",
) -> str:
    """Return an inline Lucide ``<svg>`` string, or empty string if unknown."""
    body = _ICONS.get(name)
    if body is None:
        return ""
    class_attr = f' class="{cls}"' if cls else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" '
        f'height="{size}" viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="{stroke_width}" stroke-linecap="round" '
        f'stroke-linejoin="round"{class_attr} '
        f'style="vertical-align:middle;display:inline-block;">{body}</svg>'
    )


def icon_label(name: str, text: str, size: int = 16, color: str = "currentColor",
               gap: int = 8) -> str:
    """Return an icon followed by text, vertically aligned, as inline HTML."""
    return (
        f'<span style="display:inline-flex;align-items:center;gap:{gap}px;">'
        f"{icon(name, size=size, color=color)}<span>{text}</span></span>"
    )
